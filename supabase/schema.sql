-- SilkFlow AI — demo schema for Supabase
-- IMPORTANT: policies below deliberately allow anonymous read/write for a hackathon MVP.
-- Do NOT use these policies in production. Add authentication + role-based RLS first.

create table if not exists public.shipments (
  tracking_code text primary key,
  route text not null,
  from_location text not null,
  to_location text not null,
  cargo text not null,
  weight numeric default 0,
  volume numeric default 0,
  status text default 'Создан',
  date_label text,
  eta_label text,
  sender text,
  receiver text,
  hs_code text,
  places integer default 0,
  price numeric default 0,
  delivery_method text default 'Не выбран',
  payment_status text default 'Не оплачено',
  split_decision text,
  split_confidence numeric,
  assigned_driver text,
  qr_token text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.shipment_events (
  id bigint generated by default as identity primary key,
  shipment_code text not null references public.shipments(tracking_code) on delete cascade,
  stage text not null,
  description text,
  created_at timestamptz default now()
);

create table if not exists public.delivery_jobs (
  id bigint generated by default as identity primary key,
  shipment_code text not null unique references public.shipments(tracking_code) on delete cascade,
  pickup text not null default 'Хаб Джалал-Абад',
  dropoff text not null,
  reward numeric default 0,
  status text not null default 'available',
  driver_name text,
  created_at timestamptz default now()
);

alter table public.shipments enable row level security;
alter table public.shipment_events enable row level security;
alter table public.delivery_jobs enable row level security;

-- Hackathon-only open policies
create policy "demo read shipments" on public.shipments for select to anon using (true);
create policy "demo insert shipments" on public.shipments for insert to anon with check (true);
create policy "demo update shipments" on public.shipments for update to anon using (true) with check (true);

create policy "demo read events" on public.shipment_events for select to anon using (true);
create policy "demo insert events" on public.shipment_events for insert to anon with check (true);

create policy "demo read jobs" on public.delivery_jobs for select to anon using (true);
create policy "demo insert jobs" on public.delivery_jobs for insert to anon with check (true);
create policy "demo update jobs" on public.delivery_jobs for update to anon using (true) with check (true);

create index if not exists shipment_events_shipment_idx on public.shipment_events(shipment_code, created_at);
create index if not exists delivery_jobs_status_idx on public.delivery_jobs(status, created_at);
